if doc_sec == "1. Solar PV Single-Diode Model":
    st.markdown("## 1. Solar Photovoltaic (PV) Single-Diode Model")
    st.write(
        """
        A solar cell is fundamentally a large-area p-n junction semiconductor device. Under illumination, 
        photons with energy greater than the bandgap ($h\\nu > E_g$) generate electron-hole pairs, creating 
        a photogenerated current $I_{ph}$.
        
        The standard 5-parameter single-diode implicit characteristic equation for a PV cell/module is:
        $$I = I_{ph} - I_0 \\left[ \\exp\\left( \\frac{V + I R_s}{n N_s V_t} \\right) - 1 \\right] - \\frac{V + I R_s}{R_{sh}}$$
        
        Where:
        - $I$: Net output terminal current (A)
        - $V$: Net output terminal voltage (V)
        - $I_{ph}$: Photocurrent generated by incident solar flux (A)
        - $I_0$: Diode reverse saturation current (A)
        - $R_s$: Internal series resistance (Ohms), representing semiconductor bulk resistance and metallization contacts
        - $R_{sh}$: Shunt resistance (Ohms), representing leakage currents across the p-n junction periphery
        - $n$: Diode ideality factor (dimensionless, typically $1.0 \\le n \\le 1.5$)
        - $N_s$: Number of cells in series per module
        - $V_t = \\frac{k_B T_K}{q}$: Thermal voltage per cell ($k_B = 1.381 \\times 10^{-23}\\text{ J/K}$, $q = 1.602 \\times 10^{-19}\\text{ C}$)
        """
    )
    
    st.markdown("### Exact Analytical Solution via the Lambert W Function")
    st.write(
        """
        Because $I$ appears both linearly and inside the exponential argument, the single-diode equation is 
        transcendental. Instead of iterative Newton-Raphson methods that can diverge under extreme limits, 
        we employ the exact analytical closed-form solution using the principal branch of the **Lambert W function** $W_0(z)$:
        
        Let:
        $$\\theta = \\frac{R_s R_{sh}}{R_s + R_{sh}}, \\quad a = n N_s V_t$$
        $$z = \\frac{\\theta I_0}{a} \\exp\\left( \\frac{R_{sh}(V + R_s(I_{ph} + I_0))}{a(R_s + R_{sh})} \\right)$$
        
        Then:
        $$I(V) = \\frac{R_{sh}(I_{ph} + I_0) - V}{R_s + R_{sh}} - \\frac{a}{R_s} W_0(z)$$
        
        This exact solution guarantees unconditionally stable, microsecond-speed evaluation for any voltage $V \\ge 0$.
        """
    )

elif doc_sec == "2. MPPT Principle & Optimality":
    st.markdown("## 2. MPPT Principle & Optimality Condition")
    st.write(
        """
        The electrical power delivered by the PV generator is:
        $$P(V) = V \\cdot I(V)$$
        
        Differentiating with respect to voltage:
        $$\\frac{dP}{dV} = \\frac{d(V \\cdot I)}{dV} = I + V \\frac{dI}{dV}$$
        
        At the **Maximum Power Point (MPP)**:
        $$\\frac{dP}{dV} = 0 \\iff \\frac{dI}{dV} = -\\frac{I}{V}$$
        
        This reveals three distinct operating regions on the $P-V$ curve:
        1. **Left of MPP ($V < V_{mpp}$):**
           $$\\frac{dP}{dV} > 0$$
           Voltage is below optimal. To increase power toward MPP, the controller must **increase PV terminal voltage**.
        2. **At MPP ($V = V_{mpp}$):**
           $$\\frac{dP}{dV} = 0$$
           Maximum available power is extracted. The controller must **maintain the current duty cycle**.
        3. **Right of MPP ($V > V_{mpp}$):**
           $$\\frac{dP}{dV} < 0$$
           Voltage is above optimal. To increase power toward MPP, the controller must **decrease PV terminal voltage**.
        """
    )

elif doc_sec == "3. Fuzzy Logic MPPT Controller":
    st.markdown("## 3. Fuzzy Logic MPPT Controller Design")
    st.write(
        """
        The Fuzzy Logic Controller (FLC) utilizes linguistic heuristics to overcome the limitations of 
        fixed-step hill-climbing algorithms.
        
        ### Controller Inputs
        1. **Error $E(k)$:**
           Approximates the instantaneous slope of the $P-V$ curve:
           $$E(k) = \\frac{P(k) - P(k-1)}{V(k) - V(k-1)}$$
        2. **Change in Error $CE(k)$:**
           Represents the acceleration/trend of the operating point:
           $$CE(k) = E(k) - E(k-1)$$
        
        Inputs are normalized into $[-1, 1]$:
        $$E_N(k) = \\text{clip}\\left(\\frac{E(k)}{K_E}, -1, 1\\right), \\quad CE_N(k) = \\text{clip}\\left(\\frac{CE(k)}{K_{CE}}, -1, 1\\right)$$
        
        ### Linguistic Terms
        Five terms are assigned across inputs and outputs:
        - **NB:** Negative Big
        - **NS:** Negative Small
        - **ZE:** Zero
        - **PS:** Positive Small
        - **PB:** Positive Big
        
        ### 5x5 Fuzzy Rule Base Matrix
        The rule table maps $(E, CE) \\to \\Delta D_N$. The signs are determined by the boost converter 
        physics ($R_{in} = (1-D)^2 R_{load}$):
        - When $E > 0$ ($V < V_{mpp}$), decreasing $D$ raises $V_{pv} \\implies \\Delta D < 0$ (Negative terms).
        - When $E < 0$ ($V > V_{mpp}$), increasing $D$ lowers $V_{pv} \\implies \\Delta D > 0$ (Positive terms).
        """
    )
    
    st.markdown("""
    | Error $E$ \\ $CE$ | **NB** | **NS** | **ZE** | **PS** | **PB** |
    |:---:|:---:|:---:|:---:|:---:|:---:|
    | **NB** ($V \\gg V_{mp}$) | **PB** | **PB** | **PB** | **PS** | **ZE** |
    | **NS** ($V > V_{mp}$)    | **PB** | **PS** | **PS** | **ZE** | **NS** |
    | **ZE** ($V \\approx V_{mp}$) | **PS** | **PS** | **ZE** | **NS** | **NS** |
    | **PS** ($V < V_{mp}$)    | **PS** | **ZE** | **NS** | **NS** | **NB** |
    | **PB** ($V \\ll V_{mp}$) | **ZE** | **NS** | **NB** | **NB** | **NB** |
    """)
    
    st.markdown("### Centroid Defuzzification")
    st.write(
        """
        The crisp output duty cycle adjustment is defuzzified using the center of gravity (centroid):
        $$\\Delta D_N = \\frac{\\int y \\cdot \\mu_{agg}(y) dy}{\\int \\mu_{agg}(y) dy}$$
        $$\\Delta D = K_{\\Delta D} \\cdot \\Delta D_N$$
        $$D(k+1) = \\text{clip}(D(k) + \\Delta D, D_{min}, D_{max})$$
        """
    )

elif doc_sec == "4. DC-DC Boost Converter Dynamics":
    st.markdown("## 4. DC-DC Boost Converter Averaged Dynamic Model")
    st.write(
        """
        The boost converter interfaces the PV generator to the load. In Continuous Conduction Mode (CCM), 
        the state-space averaged differential equations are:
        
        $$\\frac{d V_{pv}}{dt} = \\frac{I_{pv}(V_{pv}, G, T) - i_L}{C_{pv}}$$
        $$\\frac{d i_L}{dt} = \\frac{V_{pv} - (1 - D) V_{out} - r_L i_L}{L}$$
        $$\\frac{d V_{out}}{dt} = \\frac{(1 - D) i_L - \\frac{V_{out}}{R_{load}}}{C_{out}}$$
        
        Where:
        - $V_{pv}$: PV terminal capacitor voltage (V)
        - $i_L$: Inductor current (A), with diode non-reversal constraint ($i_L \\ge 0$)
        - $V_{out}$: Output capacitor voltage across load (V)
        - $D$: Switching duty cycle ($0 < D < 1$)
        - $L$: Inductor inductance (2.5 mH)
        - $r_L$: Inductor parasitic resistance (0.05 Ω)
        - $C_{pv}$: PV input smoothing capacitor (220 µF)
        - $C_{out}$: Output capacitor (470 µF)
        - $R_{load}$: Resistive DC load (30.0 Ω)
        
        ### Numerical Integration
        Classical 4th-order Runge-Kutta (RK4) integration is employed at time steps of $dt = 50\\text{ µs}$, 
        providing guaranteed numerical stability across high-frequency transient switching oscillations.
        """
    )

elif doc_sec == "5. Perturb & Observe (P&O) Baseline":
    st.markdown("## 5. Conventional Perturb & Observe (P&O) MPPT")
    st.write(
        """
        Perturb & Observe is the benchmark hill-climbing algorithm used worldwide in commercial inverters.
        
        ### Algorithm Logic
        Every sampling interval $T_s$:
        1. Measure $V(k)$ and $P(k)$.
        2. Calculate $\\Delta V = V(k) - V(k-1)$ and $\\Delta P = P(k) - P(k-1)$.
        3. Decision Table:
           - If $\\Delta P > 0$ and $\\Delta V > 0 \\implies D(k+1) = D(k) - \\Delta D$
           - If $\\Delta P > 0$ and $\\Delta V < 0 \\implies D(k+1) = D(k) + \\Delta D$
           - If $\\Delta P < 0$ and $\\Delta V > 0 \\implies D(k+1) = D(k) + \\Delta D$
           - If $\\Delta P < 0$ and $\\Delta V < 0 \\implies D(k+1) = D(k) - \\Delta D$
        
        ### Fundamental Limitations
        - **Fixed Step Dilemma:** Cannot simultaneously provide rapid dynamic response and zero steady-state ripple.
        - **Cloud Drift Error:** During a sudden drop in solar irradiance, $\\Delta P$ is negative while $\\Delta V$ may be positive, causing P&O to mistake the environmental change for a perturbation error and step in the wrong direction.
        """
    )

elif doc_sec == "6. Performance Metrics & Figures of Merit":
    st.markdown("## 6. Performance Evaluation Methodology")
    st.write(
        """
        ### 1. Energy Tracking Efficiency ($\\eta_{MPPT}$)
        $$\\eta_{MPPT} = \\frac{\\int_0^T P_{pv}(t) dt}{\\int_0^T P_{mpp}^*(t) dt} \\times 100\\%$$
        Evaluated numerically via Trapezoidal integration of actual measured telemetry against the 
        independently calculated theoretical reference MPP.
        
        ### 2. Settling Time ($t_s$)
        The duration required after a step transition in environmental conditions ($G$ or $T$) 
        for the tracked power $P_{pv}(t)$ to enter and continuously remain within a $\\pm 2\\%$ error 
        band around the new steady-state $P_{mpp}^*$:
        $$\\left| \\frac{P_{pv}(t) - P_{mpp}^*}{P_{mpp}^*} \\right| \\le 0.02, \\quad \\forall t \\ge t_{trans} + t_s$$
        
        ### 3. Steady-State Oscillation Amplitude ($\\Delta P_{osc}$)
        Peak-to-peak power ripple during the final $20\\%$ steady-state interval:
        $$\\Delta P_{osc} = \\max(P_{pv}) - \\min(P_{pv})$$
        $$\\sigma_{P} = \\sqrt{\\frac{1}{N} \\sum (P_{pv, i} - \\bar{P}_{pv})^2}$$
        """
    )
